from tradingagents.agents.context import (
    STRICT_PRICE_AND_EVIDENCE_RULES,
    get_instrument_context_from_state,
    get_language_instruction,
    get_portfolio_context_from_state,
    opponent_argument_or_opening,
    report_or_absent,
)


def create_aggressive_debator(llm):
    def aggressive_node(state) -> dict:
        risk_debate_state = state["risk_debate_state"]
        history = risk_debate_state.get("history", "")
        aggressive_history = risk_debate_state.get("aggressive_history", "")

        current_conservative_response = opponent_argument_or_opening(
            risk_debate_state.get("current_conservative_response", ""), "conservative analyst"
        )
        current_neutral_response = opponent_argument_or_opening(
            risk_debate_state.get("current_neutral_response", ""), "neutral analyst"
        )

        market_research_report = report_or_absent(state["market_report"], "market")
        sentiment_report = report_or_absent(state["sentiment_report"], "sentiment")
        news_report = report_or_absent(state["news_report"], "news")
        fundamentals_report = report_or_absent(state["fundamentals_report"], "fundamentals")
        instrument_context = get_instrument_context_from_state(state)
        portfolio_context = get_portfolio_context_from_state(state)
        trader_decision = state["trader_investment_plan"]

        prompt = f"""As the Aggressive Risk Analyst, evaluate the trader's proposal from a risk-tolerant, upside-seeking perspective, while adhering strictly to verified evidence.

{STRICT_PRICE_AND_EVIDENCE_RULES}

Here is the trader's decision:
{trader_decision}

Sources available:
{instrument_context}
{portfolio_context}
Market Research Report: {market_research_report}
Social Media Sentiment Report: {sentiment_report}
Latest World Affairs Report: {news_report}
Company Fundamentals Report: {fundamentals_report}
Current conversation history: {history}
Last arguments from the conservative analyst: {current_conservative_response}
Last arguments from the neutral analyst: {current_neutral_response}

If there are no responses from the other viewpoints yet, open with your own evidence-grounded case. Challenge overly cautious assumptions using ONLY verified figures from the reports above, acknowledge any `Insufficient Data` (`DATA_UNAVAILABLE`) blind spots honestly without inventing company/macro facts, and NEVER invent arbitrary price targets, supports, resistances, or stop-losses (state explicitly when no validated technical level exists). Output conversationally without special formatting.""" + get_language_instruction()

        response = llm.invoke(prompt)

        argument = f"Aggressive Analyst: {response.content}"

        new_risk_debate_state = {
            "history": history + "\n" + argument,
            "aggressive_history": aggressive_history + "\n" + argument,
            "conservative_history": risk_debate_state.get("conservative_history", ""),
            "neutral_history": risk_debate_state.get("neutral_history", ""),
            "latest_speaker": "Aggressive",
            "current_aggressive_response": argument,
            "current_conservative_response": risk_debate_state.get("current_conservative_response", ""),
            "current_neutral_response": risk_debate_state.get("current_neutral_response", ""),
            "count": risk_debate_state["count"] + 1,
        }

        return {"risk_debate_state": new_risk_debate_state}

    return aggressive_node
